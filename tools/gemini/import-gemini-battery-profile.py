"""Emit Gemini's OCV data from the pinned, active vendor battery header.

Usage: import-gemini-battery-profile.py VENDOR_SOURCE > PROFILE.dtsi

The HAFG_20 header initializer supplies these tables to the fuel-gauge
daemon. Its voltage lookup calls them ZCV profiles. They describe the
original pack, not a measurement of the installed battery's health.
"""

import argparse
import hashlib
from pathlib import Path
import re


HEADER = Path("drivers/misc/mediatek/include/mt-plat/mt6797/include/mach/"
              "mt_battery_meter_table.h")
HEADER_SHA256 = "4c9e88e7ba722e9ff2c53373e9a3d2cf851c8f0599aa2748e1d95bbee3715d9d"
CONFIG_HEADER = HEADER.with_name("mt_battery_meter.h")
CONFIG_SHA256 = "14ed0f8a50244647deb9ffd2af2f02ae7a6725d6da6181c26d9cd756a1dfc68d"
TEMPERATURES = (-10, 0, 25, 50)


def extract_profile(source, index):
    matches = re.findall(
        rf"BATTERY_PROFILE_STRUCT battery_profile_t{index}\[\]\s*=\s*"
        r"\{(.*?)\};", source, re.S)
    if len(matches) != 1:
        raise ValueError(f"expected one battery_profile_t{index}")
    body = re.sub(r"/\*.*?\*/|//[^\n]*", "", matches[0], flags=re.S)
    entries = re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*\}", body)
    remainder = re.sub(r"\{\s*\d+\s*,\s*\d+\s*\}", "", body)
    if remainder.strip(" \t\r\n,"):
        raise ValueError("unparsed profile data")
    pairs = [tuple(map(int, pair)) for pair in entries]
    if len(pairs) != 96 or pairs[0][0] != 0 or pairs[-1] != (100, 3400):
        raise ValueError("unexpected vendor profile shape")

    result = []
    for dod, mv in pairs:
        if not 0 <= dod <= 100 or not 3000 <= mv <= 4500:
            raise ValueError("invalid depth of discharge or voltage")
        point = (mv * 1000, 100 - dod)
        if result:
            previous = result[-1]
            if point == previous:
                continue
            if point[0] >= previous[0] or point[1] > previous[1]:
                raise ValueError("ambiguous or nonmonotonic profile")
        result.append(point)
    return result


def extract_resistance(source, index):
    blocks = re.findall(rf"R_PROFILE_STRUCT r_profile_t{index}\[\]\s*=\s*"
                        r"\{(.*?)\};", source, re.S)
    if len(blocks) != 1:
        raise ValueError("expected one resistance table")
    pairs = [tuple(map(int, pair)) for pair in
             re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*\}", blocks[0])]
    if len(pairs) != 96:
        raise ValueError("unexpected resistance table length")
    result = []
    for mohm, mv in pairs:
        point = (mv * 1000, mohm * 1000)
        if not 3000 <= mv <= 4500 or not 0 < mohm <= 20000:
            raise ValueError("invalid resistance table units")
        if result and result[-1] == point:
            continue
        if result and point[0] >= result[-1][0]:
            raise ValueError("ambiguous or nonmonotonic resistance table")
        result.append(point)
    if [v for v, r in result] != [v for v, c in extract_profile(source, index)]:
        raise ValueError("voltage grids differ")
    return result


def render(source, config):
    lines = [
        "// SPDX-License-Identifier: GPL-2.0-only",
        "/*",
        " * Copyright (C) 2015 MediaTek Inc.",
        " *",
        " * Original Gemini battery ZCV profiles from vendor revision 51e705e4.",
        " * Source: mt6797/include/mach/mt_battery_meter_table.h, active HAFG_20",
        " * header initialization (not the generic vendor device tree).",
        " * Generated by tools/gemini/import-gemini-battery-profile.py.",
        " * Convert mV to uV and depth of discharge to remaining percent;",
        " * remove only identical consecutive points. T0 means -10 C; the",
        " * vendor TEMPERATURE_T0 value 110 is a selector, not a temperature.",
        " * These profiles do not specify measured capacity, aging, charger",
        " * limits or installed-pack calibration. Qmax is not design capacity.",
        " */",
        "",
        "/ {",
        "\tgemini_battery: battery {",
        '\t\tcompatible = "simple-battery";',
        "\t\tocv-capacity-celsius = <(-10) 0 25 50>;",
    ]
    for index, temp in enumerate(TEMPERATURES):
        points = extract_profile(source, index)
        lines += ["", f"\t\t/* {temp} degrees Celsius. */",
                  f"\t\tocv-capacity-table-{index} ="]
        for i, (uv, capacity) in enumerate(points):
            suffix = ";" if i == len(points) - 1 else ","
            lines.append(f"\t\t\t<{uv} {capacity}>{suffix}")
    lines += ["\t};", "};", "", "&mt6351fgadc {",
              "\t/* Header Qmax is an estimator input, not charge-full-design. */",
              "\tmediatek,capacity-model ="]
    names = ("NEG_10", "POS_0", "POS_25", "POS_50")
    for i, (temp, name) in enumerate(zip(TEMPERATURES, names)):
        qmax = int(re.search(rf"^#define Q_MAX_{name}\s+(\d+)\s*$", config, re.M)[1])
        temp_cell = f"({temp})" if temp < 0 else str(temp)
        suffix = ";" if i == 3 else ","
        lines.append(f"\t\t<{temp_cell} {qmax * 1000}>{suffix}")
    for index, temp in enumerate(TEMPERATURES):
        points = extract_resistance(source, index)
        lines += ["", f"\t/* {temp} degrees Celsius: uV, uOhm. */",
                  f"\tmediatek,resistance-table-{index} ="]
        for i, (uv, uohm) in enumerate(points):
            suffix = ";" if i == len(points) - 1 else ","
            lines.append(f"\t\t<{uv} {uohm}>{suffix}")
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("vendor_source", type=Path)
    args = parser.parse_args()
    raw = (args.vendor_source / HEADER).read_bytes()
    if hashlib.sha256(raw).hexdigest() != HEADER_SHA256:
        parser.error("vendor header hash differs; review its provenance first")
    config = (args.vendor_source / CONFIG_HEADER).read_bytes()
    if hashlib.sha256(config).hexdigest() != CONFIG_SHA256:
        parser.error("vendor Qmax header hash differs; review its provenance first")
    print(render(raw.decode(), config.decode()), end="")


if __name__ == "__main__":
    main()
