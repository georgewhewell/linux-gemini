class FormatTests(unittest.TestCase):
    def test_literal_checksums_and_every_split(self):
        # Independently hand-calculated words: XOR1, ADD2, XOR4, ADD8 =>15.
        vectors = [(b'', 0), (b'\x01', 0), (b'\x01\x02', 0x203),
                   (b'\x01\x02\x03', 0x30202),
                   (struct.pack('<4I', 1, 2, 4, 8), 31),
                   (struct.pack('<2I', 0xffffffff, 2), 9),
                   (struct.pack('<I', 0xffffffff) + b'\x02', 4),
                   (struct.pack('<2I', 1, 2) + b'\x04\x05\x06', 0x6050c)]
        for data, expected in vectors:
            for split in range(len(data) + 1):
                c = Checksum()
                c.update(data[:split])
                c.digest()  # Mid-word snapshots must not finalize state.
                c.update(b'')
                c.update(data[split:])
                self.assertEqual(c.digest(), expected)
                self.assertEqual(c.digest(), expected)
            c = Checksum()
            for value in data:
                c.update(bytes([value]))
            self.assertEqual(c.digest(), expected)
            verify_checksum(struct.pack('<III', expected, 0x1234, 0x5678), data)
            with self.assertRaises(FormatError):
                verify_checksum(struct.pack('<III', expected ^ 1, 0, 0), data)

    def test_limit_and_rejected_update_is_atomic(self):
        c = Checksum()
        block = bytes(65536)
        for _ in range(MAX_BYTES // len(block)):
            c.update(block)
        self.assertEqual(c.digest(), MAX_BYTES)
        with self.assertRaises(FormatError):
            c.update(b'x')
        self.assertEqual(c.digest(), MAX_BYTES)
        for size in range(12):
            with self.assertRaises(FormatError):
                verify_checksum(bytes(size), b'')
        with self.assertRaises(TypeError):
            c.update(bytearray())

    @staticmethod
    def record(offset=2, length=3, name=b'/data/nvram/test'):
        return struct.pack('<III', 0xaabbccdd, offset, length) + name.ljust(128, b'\0')

    def test_record_extent_and_opaque_bytes(self):
        r = decode_record(self.record(), 5)
        self.assertEqual((r.opaque, r.offset, r.length, r.name),
                         (0xaabbccdd, 2, 3, b'/data/nvram/test'))
        self.assertEqual(decode_record(self.record(5, 0), 5).length, 0)
        self.assertEqual(decode_record(self.record(0, 0), 0).length, 0)
        self.assertEqual(decode_record(self.record(0, MAX_BYTES), MAX_BYTES).length,
                         MAX_BYTES)
        # No text transcoding or path authorization is performed here.
        self.assertEqual(decode_record(self.record(name=b'../\xff'), 5).name, b'../\xff')
        self.assertEqual(len(decode_record(self.record(name=b'a'*127), 5).name), 127)
        for offset, length in [(6, 0), (2, 4), (0xffffffff, 2), (1, 0xffffffff)]:
            with self.assertRaises(FormatError):
                decode_record(self.record(offset, length), 5)
        for size in [-1, MAX_BYTES + 1, True, 1.5]:
            with self.assertRaises(FormatError):
                decode_record(self.record(), size)
        for data in [self.record()[:-1], self.record()+b'x',
                     self.record(name=b''), self.record(name=b'a'*128)]:
            with self.assertRaises(FormatError):
                decode_record(data, 5)


class ReconstructionTests(unittest.TestCase):
    @staticmethod
    def fixture(*, layout=0, file_size=ERASE_BYTES + 3):
        # Ten physical blocks. Layout0: six usable, five map bytes;
        # map in block4, header0, data1+3, block2 excluded. Nonzero map
        # bytes are excluded regardless of their exact value.
        raw = bytearray(b'\xff' * (10 * ERASE_BYTES))
        count = 5 if layout == 0 else 9
        bitmap = bytes([0, 0, 0x81, 0] + [1] * (count - 4))
        start = 4 * ERASE_BYTES
        raw[start:start + 3*count + 4] = bitmap*3 + struct.pack('<I', MAP_MAGIC)
        # Data consists of zero complete words plus tail 01 02 03. The
        # expected checksum is hand-calculated, not generated by the parser.
        data = bytes(file_size)
        expected = file_size
        if file_size == ERASE_BYTES + 3:
            data = bytes(ERASE_BYTES) + b'\x01\x02\x03'
            expected = 0x30201 ^ file_size
        allmap = struct.pack('<III', expected, 0x11223344, 0x55667788)
        struct.pack_into('<III', raw, 0, len(allmap), file_size, 0x12345678)
        raw[12:24] = allmap
        for i, block in enumerate((1, 3)):
            part = data[i*ERASE_BYTES:(i+1)*ERASE_BYTES]
            raw[block*ERASE_BYTES:block*ERASE_BYTES+len(part)] = part
        return raw, allmap, data

    def test_noncontiguous_data_and_padding(self):
        for layout in (0, 1):
            raw, allmap, data = self.fixture(layout=layout)
            result = reconstruct(bytes(raw), layout_version=layout)
            self.assertEqual((result.allmap, result.allfile), (allmap, data))
            self.assertEqual((result.map_block, result.header_block, result.data_blocks),
                             (4, 0, (1, 3)))
            self.assertNotIn('allfile', repr(result))
        for size in (0, 1, 4, ERASE_BYTES):
            raw, allmap, data = self.fixture(file_size=size)
            self.assertEqual(reconstruct(bytes(raw)).allfile, data)

    def test_two_block_map_with_gap(self):
        # Header in0 and2, block1 excluded; data in3. Map block4.
        raw, _, _ = self.fixture(file_size=4)
        for map_size in (ERASE_BYTES-12, ERASE_BYTES-11, 143132,
                         2*ERASE_BYTES-12):
            image = raw.copy()
            allmap = struct.pack('<III', 4, 0, 0) + bytes(map_size-12)
            header = struct.pack('<III', map_size, 4, 0) + allmap
            image[:ERASE_BYTES] = header[:ERASE_BYTES]
            second = header[ERASE_BYTES:]
            image[2*ERASE_BYTES:2*ERASE_BYTES+len(second)] = second
            bitmap = bytes([0, 1, 0, 0, 1])
            image[4*ERASE_BYTES:4*ERASE_BYTES+19] = bitmap*3 + struct.pack('<I', MAP_MAGIC)
            data_block = 3 if second else 2
            image[data_block*ERASE_BYTES:data_block*ERASE_BYTES+4] = bytes(4)
            result = reconstruct(bytes(image))
            self.assertEqual(result.allmap, allmap)
            self.assertEqual(result.allfile, bytes(4))
            self.assertEqual(result.data_blocks, (data_block,))
        # Two map blocks leave no data authority when only two zeros exist.
        bitmap = bytes([0, 1, 0, 1, 1])
        image[4*ERASE_BYTES:4*ERASE_BYTES+19] = bitmap*3 + struct.pack('<I', MAP_MAGIC)
        with self.assertRaises(FormatError):
            reconstruct(bytes(image))

    def test_header_can_follow_excluded_blocks(self):
        raw, allmap, data = self.fixture(file_size=4)
        header = bytes(raw[:ERASE_BYTES])
        raw[ERASE_BYTES:2*ERASE_BYTES] = header
        raw[3*ERASE_BYTES:3*ERASE_BYTES+4] = data
        bitmap = bytes([1, 0, 0xff, 0, 1])
        raw[4*ERASE_BYTES:4*ERASE_BYTES+19] = bitmap*3 + struct.pack('<I', MAP_MAGIC)
        result = reconstruct(bytes(raw))
        self.assertEqual((result.header_block, result.data_blocks), (1, (3,)))
        self.assertEqual((result.allmap, result.allfile), (allmap, data))
        # A magic-bearing block in the excluded tail cannot supersede it.
        raw[9*ERASE_BYTES:9*ERASE_BYTES+19] = bytes(15) + struct.pack('<I', MAP_MAGIC)
        self.assertEqual(reconstruct(bytes(raw)).map_block, 4)

    def test_map_disagreement_and_magic(self):
        original, _, _ = self.fixture()
        for position in (4*ERASE_BYTES, 4*ERASE_BYTES+5,
                         4*ERASE_BYTES+10, 4*ERASE_BYTES+15):
            raw = original.copy()
            raw[position] ^= 1
            with self.assertRaises(FormatError):
                reconstruct(bytes(raw))
        # An invalid higher candidate is skipped, preserving lower valid map.
        raw, _, data = self.fixture(layout=1)
        raw[8*ERASE_BYTES:8*ERASE_BYTES+31] = bytes(27) + struct.pack('<I', MAP_MAGIC ^ 1)
        self.assertEqual(reconstruct(bytes(raw), layout_version=1).allfile, data)
        # A valid higher map pointing at malformed header fails rather than
        # falling back to the lower valid map.
        bitmap = bytes([1, 1, 0, 1, 1, 0, 1, 1, 1])
        raw[8*ERASE_BYTES:8*ERASE_BYTES+31] = bitmap*3 + struct.pack('<I', MAP_MAGIC)
        with self.assertRaises(FormatError):
            reconstruct(bytes(raw), layout_version=1)

    def test_lengths_corruption_and_geometry(self):
        original, _, _ = self.fixture()
        for map_size, file_size in [(11, 0), (2*ERASE_BYTES-11, 0),
                                    (0xffffffff, 1), (12, MAX_BYTES+1),
                                    (12, 2*ERASE_BYTES+1)]:
            raw = original.copy()
            struct.pack_into('<II', raw, 0, map_size, file_size)
            with self.assertRaises(FormatError):
                reconstruct(bytes(raw))
        raw = original.copy()
        raw[ERASE_BYTES] ^= 1
        with self.assertRaises(FormatError):
            reconstruct(bytes(raw))
        for raw in (b'', bytes(ERASE_BYTES), bytes(original[:-1]),
                    bytes(MAX_BYTES+ERASE_BYTES)):
            with self.assertRaises(FormatError):
                reconstruct(raw)
        for version in (-1, 2, True, 0.0):
            with self.assertRaises(FormatError):
                reconstruct(bytes(original), layout_version=version)
        with self.assertRaises(TypeError):
            reconstruct(original)
        for bitmap in (bytes([1]*5), bytes([0, 1, 1, 1, 0])):
            raw = original.copy()
            raw[4*ERASE_BYTES:4*ERASE_BYTES+19] = bitmap*3 + struct.pack('<I', MAP_MAGIC)
            with self.assertRaises(FormatError):
                reconstruct(bytes(raw))


class GroupTests(unittest.TestCase):
    @staticmethod
    def fixture():
        # A distinct record per physical count slot; no implementation-derived
        # checksum, since the four zero data bytes checksum to4.
        header = struct.pack('<III16H', 4, 0, 0, *([1]*16)) + bytes(8)
        records = b''.join(struct.pack('<III', 0, 0, 4) +
                           ('/fixture/%d' % i).encode().ljust(128, b'\0')
                           for i in range(16))
        return Backup(header + records, bytes(4), 4, 0, (1,))

    def test_profile_gates_and_selection(self):
        backup = self.fixture()
        for md5, md3, expected in (
                (True, True, [0,1,2,3,4,7,8,9,10,11,12,14,15,16]),
                (False, True, [0,1,2,3,4,7,8,9,14,15,16]),
                (False, False, [0,1,2,3,4,7,8,9,14,15,16]),
                (True, False, [0,1,2,3,4,7,8,9,10,11,12,14,15,16])):
            records = parse_ecci_records(backup, md5=md5, md3=md3,
                                         ecci=True, header_offset=0)
            self.assertEqual([g for g, _ in records], expected)
            self.assertEqual(select_record(records, b'/fixture/13').length, 4)
            self.assertEqual(next(g for g,r in records if r.name==b'/fixture/13'), 14)
            for name in (b'/fixture/5', b'/fixture/6', b'/FIXTURE/0', b'/fixture/missing'):
                with self.assertRaises(FormatError):
                    select_record(records, name)
        for kwargs in (dict(md5=0, md3=True, ecci=True, header_offset=0),
                       dict(md5=False, md3=True, ecci=False, header_offset=0),
                       dict(md5=False, md3=True, ecci=True, header_offset=1)):
            with self.assertRaises(FormatError):
                parse_ecci_records(backup, **kwargs)

    def test_first_match_and_invalid_names(self):
        records = parse_ecci_records(self.fixture(), md5=True, md3=True,
                                     ecci=True, header_offset=0)
        first = records[0][1]
        self.assertIs(select_record(((0,first),(1,first)), first.name), first)
        self.assertNotIn('/fixture', repr(records))
        for name in (b'', b'a'*128, b'a\0b'):
            with self.assertRaises(FormatError):
                select_record(records, name)
        with self.assertRaises(TypeError):
            select_record(records, '/fixture/0')

    def test_entire_map_validation(self):
        b = self.fixture()
        bad_maps = [b.allmap[:51], b.allmap[:-1], b.allmap+b'x']
        for value in (0x7fff, 0x8000, 0xffff, 2):
            m = bytearray(b.allmap)
            struct.pack_into('<H', m, 12, value)
            bad_maps.append(bytes(m))
        # Corruption in an excluded group must still fail validation.
        m = bytearray(b.allmap)
        struct.pack_into('<I', m, 52+5*140+4, 5)
        bad_maps.append(bytes(m))
        for m in bad_maps:
            with self.assertRaises(FormatError):
                parse_ecci_records(Backup(m,b.allfile,4,0,(1,)), md5=False,
                                   md3=True,ecci=True,header_offset=0)



class TargetTests(unittest.TestCase):
    def test_exact_roots_and_unicode(self):
        for root, drive in ((b'/data/nvram/md', 'Z'), (b'/protect_f/md', 'X'),
                            (b'/protect_s/md', 'Y')):
            self.assertEqual(modem_target(root+b'/NVRAM/file'), (drive,b'NVRAM/file'))
            self.assertEqual(modem_target(root+'/café'.encode()), (drive,'café'.encode()))
        for name in (b'/data/nvram/md3/file', b'/data/nvram/md_cmn/file',
                     b'/data/nvram/md2/file', b'/protect_f/md5/file',
                     b'/nvdata/md/file', b'/data/nvram/APCFG/file', b'/etc/passwd',
                     b'data/nvram/md/file', b'/data/nvram/md-other/file'):
            self.assertIsNone(modem_target(name))

    def test_refuses_aliases_and_escape(self):
        for suffix in (b'', b'/', b'/../file', b'/a/../../file', b'/./file',
                       b'/a//b', b'/a/', b'/a\\b', b'/Z:file', b'/a\0b',
                       b'/a\nb', b'/\xff', b'/'+b'a'*256,
                       b'/'+b'a/'*513+b'a'):
            with self.assertRaises(FormatError):
                modem_target(b'/data/nvram/md'+suffix)
        with self.assertRaises(TypeError):
            modem_target('/data/nvram/md/file')


